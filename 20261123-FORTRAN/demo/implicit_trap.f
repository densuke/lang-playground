C     固定形式は空白に意味がない。そのため DO 文の書き間違い 1 つで、
C     ループではなく「DO10I という名前の変数への代入」になる。
C     (DO 10 I = 1,10 のカンマをピリオドに打ち間違えた形)
C     変数宣言も要らないので、コンパイラは何も言わない。
      PROGRAM TRAP
      I = 0
      DO 10 I = 1.10
      WRITE (*, *) 'ループの中 I =', I
   10 CONTINUE
      WRITE (*, *) 'DO10I =', DO10I
      END
